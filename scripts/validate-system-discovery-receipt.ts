import assert from 'node:assert/strict';
import * as receipt from '../lib/server/content/system-discovery-receipt';
const t='2026-10-17T00:00:00.000Z',later='2026-10-17T01:00:00.000Z';
assert.equal(typeof receipt.mergeSystemDiscoveryReceipt,'function');
const first=receipt.mergeSystemDiscoveryReceipt(undefined,false,true,t);
assert.equal(receipt.firstSystemDiscoveryAt(first),t);
assert.equal(receipt.firstSystemDiscoveryAt(receipt.mergeSystemDiscoveryReceipt(first,true,true,later)),t);
const manual=receipt.mergeSystemDiscoveryReceipt(undefined,false,false,t);
assert.equal(receipt.firstSystemDiscoveryAt(manual),null);
assert.equal(receipt.firstSystemDiscoveryAt(receipt.mergeSystemDiscoveryReceipt(manual,true,true,later)),later);
const legacy=receipt.mergeSystemDiscoveryReceipt(undefined,true,true,later);
assert.equal(receipt.firstSystemDiscoveryAt(legacy),null,'LEGACY_HAS_NO_PROVABLE_FIRST_SYSTEM_TIME');
assert.equal(legacy.firstKnownSystemAt,later);
assert.equal(receipt.firstSystemDiscoveryAt(receipt.mergeSystemDiscoveryReceipt(legacy,true,true,'2026-10-17T02:00:00Z')),null);
assert.equal(receipt.firstSystemDiscoveryAt({...first,firstKnownSystemAt:'2099-01-01T00:00:00Z'}),null);
assert.equal(typeof receipt.firstSystemDiscoveryAcrossSources,'function');
assert.equal(receipt.firstSystemDiscoveryAcrossSources([legacy,first]),null,'NEW_SOURCE_CANNOT_MASK_UNKNOWN_HISTORY');
assert.equal(receipt.firstSystemDiscoveryAcrossSources([first,receipt.mergeSystemDiscoveryReceipt(undefined,false,true,later)]),t);
console.log('SYSTEM_DISCOVERY_RECEIPT=PASS');
